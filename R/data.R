#' Generate the benchmark data
#'
#' Every task runs on one data set: a few tables generated from a fixed seed
#' with fixed random number generators, so every machine runs on the same
#' data. Generation runs in a separate R process, so the memory it takes is
#' released when it is done. Tables are cached as uncompressed Parquet files
#' and reused.
#'
#' @section Data sets:
#' * `"arena"`, tidyarena's own: `df`, the main table, and `lookup`, a small
#'   dimension table. `df` has these columns:
#'   * `id`: row number, integer.
#'   * `g_low`: 10 groups, character (`"k01"` to `"k10"`).
#'   * `g_high`: `n / 100` groups, integer, uniform.
#'   * `g_skew`: 10,000 groups, integer, Zipf distributed.
#'   * `x`: standard normal, double.
#'   * `y`: uniform on (0, 1), double.
#'   * `z`: integer from 1 to 100, 5% missing.
#'   * `s`: 1,000 distinct strings, character.
#'
#'   `lookup` has one row per `g_high` value with columns `g_high`, `region`
#'   (five regions) and `weight`.
#' * `"dbbench_groupby"` and `"dbbench_join"`: the data of db-benchmark
#'   (<https://github.com/duckdblabs/db-benchmark>), generated as its
#'   `groupby-datagen.R` and `join-datagen.R` do (100 groups, no missing
#'   values, unsorted), so the tables equal the ones its published results
#'   come from. `x` for the groupby questions; `x`, `small`, `medium` and
#'   `big` for the joins, which need at least 1e7 rows.
#' * `"joins"`: tidyarena's join data. `events`, n rows, with a key as
#'   integer (`key_int`), string (`key_chr`) and factor (`key_fct`), a time
#'   `t` and a value `x`; `dim` and `cats` to join on them, with keys
#'   missing on both sides and factor levels in another order; `prices`,
#'   prices changing over time for rolling joins; `bands` and `windows`,
#'   value and time ranges for non-equi joins.
#' * `"strings"`: tidyarena's string data, one table `customers` with messy
#'   names, emails, product codes, free text and dates stored as strings.
#' * `"datetimes"`: tidyarena's date and time data, one table `log` with
#'   timestamps in UTC over 2023 to 2025 (`ts`, and `ts_end` up to two hours
#'   later), their `date`, the timestamp as a string (`ts_str`), a `user`
#'   and an `amount`.
#' * `"tpch"`: the eight tables of the TPC-H schema, generated by DuckDB's
#'   `dbgen()` at scale factor `n / 1e7` (scale factor 1, about 8.7 million
#'   rows in all, at `n = 1e7`). Needs duckdb.
#'
#' @param n Number of rows: of `df` for `"arena"`, of `x` for the
#'   db-benchmark data sets, and `1e7` times the scale factor for `"tpch"`.
#' @param dir Directory for the cached tables.
#' @param dataset Data set, see below.
#' @returns A list with `tables`, the paths of the tables by name, and
#'   `fingerprint`, a summary of the data to check it against other machines.
#' @export
#' @examples
#' \dontrun{
#' arena_data(1e5, tempfile())
#' arena_data(1e7, dataset = "dbbench_join")
#' }
arena_data <- function(n, dir = arena_cache_dir(), dataset = "arena") {
  check_size(n)
  def <- dataset_def(dataset)
  if (n < def$min_size) {
    cli::cli_abort("The {.val {dataset}} data set needs at least {format_n(def$min_size)} rows.")
  }
  dir <- dataset_dir(dir, dataset, n)
  tables <- as.list(stats::setNames(file.path(dir, paste0(def$tables, ".parquet")), def$tables))
  fingerprint_path <- file.path(dir, "fingerprint.rds")
  if (all(file.exists(c(unlist(tables), fingerprint_path)))) {
    return(list(tables = tables, fingerprint = readRDS(fingerprint_path)))
  }

  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  # Tables cached as .rds by earlier versions.
  unlink(file.path(dir, c("df.rds", "lookup.rds")))
  generate <- def$generate
  environment(generate) <- globalenv()
  fingerprint <- callr::r(
    function(generate, n, seed, paths, options) {
      fingerprint <- generate(n, seed, paths, options)
      saveRDS(fingerprint, paths$fingerprint)
      fingerprint
    },
    args = list(
      generate = generate,
      n = n,
      seed = def$seed,
      paths = c(tables, fingerprint = fingerprint_path),
      options = list(lib = arena_lib(), cache = arena_cache_dir())
    ),
    libpath = c(.libPaths(), arena_lib())
  )
  list(tables = tables, fingerprint = fingerprint)
}

# The data sets: their tables, how they are generated, and the in-memory
# size of their tables in bytes for `n` rows, which the plan uses to estimate
# peak memory. `generate` runs in a fresh R process with base R and
# nanoparquet (and duckdb for TPC-H); it writes every table in `paths` and
# returns a fingerprint. `gen_factor` is the memory generation takes,
# relative to the data.
dataset_defs <- function() {
  list(
    arena = list(
      version = 2L,
      dir = "gen2",
      tables = c("df", "lookup"),
      seed = generator_seed,
      generate = generate_tables,
      # 4 integer, 2 double and 2 character columns.
      bytes = function(n) n * (4 * 4 + 2 * 8 + 2 * 8) * 1.05,
      gen_factor = 3,
      min_size = 1
    ),
    dbbench_groupby = list(
      version = 2L,
      tables = "x",
      seed = 108L,
      generate = generate_dbbench_groupby,
      # 3 factor, 5 integer and 1 double columns.
      bytes = function(n) n * (8 * 4 + 8) * 1.05,
      gen_factor = 3,
      min_size = 100
    ),
    dbbench_join = list(
      version = 2L,
      tables = c("x", "small", "medium", "big"),
      seed = 108L,
      generate = generate_dbbench_join,
      # x and big: 3 integer, 3 factor and 1 double columns, with n levels
      # in one of the factors.
      bytes = function(n) 2 * n * (6 * 4 + 8 + 64) * 1.05,
      gen_factor = 3,
      min_size = 1e7
    ),
    joins = list(
      version = 2L,
      tables = c("events", "dim", "cats", "prices", "bands", "windows"),
      seed = 20261115L,
      generate = generate_joins,
      # events: 4 integer, 1 character, 1 factor, 1 double columns and n / 10
      # strings; dim and prices: n / 10 rows each.
      bytes = function(n) n * (5 * 4 + 8 + 8 + 6 + 3 + 2) * 1.05,
      gen_factor = 3,
      min_size = 1e4
    ),
    strings = list(
      version = 2L,
      tables = "customers",
      seed = 20261116L,
      generate = generate_strings,
      # 5 character columns, one of nearly unique sentences: about 330
      # bytes per row, measured.
      bytes = function(n) n * 340,
      gen_factor = 3,
      min_size = 1e3
    ),
    datetimes = list(
      version = 2L,
      tables = "log",
      seed = 20261117L,
      generate = generate_datetimes,
      # 2 integer, 4 date and time, 1 double columns, and nearly unique
      # timestamp strings.
      bytes = function(n) n * (2 * 4 + 4 * 8 + 8 + 8 + 70) * 1.05,
      gen_factor = 3,
      min_size = 1e3
    ),
    tpch = list(
      version = 1L,
      tables = c(
        "customer", "lineitem", "nation", "orders",
        "part", "partsupp", "region", "supplier"
      ),
      seed = NA_integer_,
      generate = generate_tpch,
      # About 1.2 GB per scale factor in R, mostly lineitem's strings.
      bytes = function(n) n * 120,
      # DuckDB generates into a file and can spill to disk.
      gen_factor = 1,
      min_size = 1e5
    )
  )
}

dataset_def <- function(dataset, call = rlang::caller_env()) {
  defs <- dataset_defs()
  check_ids(dataset, names(defs), "dataset", call = call)
  defs[[dataset]]
}

dataset_dir <- function(dir, dataset, n) {
  def <- dataset_def(dataset)
  file.path(dir, def$dir %||% paste0(dataset, "-v", def$version), format_n(n))
}

# In-memory size of a data set's tables, in bytes.
data_bytes <- function(n, dataset = "arena") {
  dataset <- rep_len(dataset, length(n))
  vapply(seq_along(n), function(i) dataset_def(dataset[[i]])$bytes(n[[i]]), numeric(1))
}

# Bytes the cached tables take on disk: Parquet stores repeated strings
# once per page.
data_disk_bytes <- function(n, dataset = "arena") {
  data_bytes(n, dataset) * 0.7
}

generator_version <- 1L
generator_seed <- 20261114L

# Runs in a fresh R process: base R, and nanoparquet to write the tables.
generate_tables <- function(n, seed, paths, options = list()) {
  # No min/max statistics: nanoparquet 0.5.2 writes wrong ones for columns
  # of more than one page, and readers that trust them, DuckDB among them,
  # then skip rows that match.
  no_minmax <- nanoparquet::parquet_options(write_minmax_values = FALSE)
  set.seed(
    seed,
    kind = "Mersenne-Twister",
    normal.kind = "Inversion",
    sample.kind = "Rejection"
  )
  n <- as.integer(n)
  n_high <- max(1L, n %/% 100L)
  n_skew <- 10000L
  strings <- sprintf("s%04d", seq_len(1000L) * 7L)

  z <- sample.int(100L, n, replace = TRUE)
  z[stats::runif(n) < 0.05] <- NA_integer_
  df <- data.frame(
    id = seq_len(n),
    g_low = sprintf("k%02d", sample.int(10L, n, replace = TRUE)),
    g_high = sample.int(n_high, n, replace = TRUE),
    g_skew = sample.int(
      n_skew,
      n,
      replace = TRUE,
      prob = 1 / seq_len(n_skew)^1.1
    ),
    x = stats::rnorm(n),
    y = stats::runif(n),
    z = z,
    s = sample(strings, n, replace = TRUE)
  )
  lookup <- data.frame(
    g_high = seq_len(n_high),
    region = sample(c("north", "south", "east", "west", "centre"), n_high, TRUE),
    weight = stats::runif(n_high)
  )

  fingerprint <- list(
    nrow = n,
    sum_x = sum(df$x),
    sum_y = sum(df$y),
    sum_z = sum(as.double(df$z), na.rm = TRUE),
    n_na_z = sum(is.na(df$z)),
    sum_skew = sum(as.double(df$g_skew))
  )
  nanoparquet::write_parquet(df, paths$df, compression = "uncompressed", options = no_minmax)
  nanoparquet::write_parquet(lookup, paths$lookup, compression = "uncompressed", options = no_minmax)
  fingerprint
}

#' Where tidyarena keeps its files
#'
#' Generated data and run results live in the user cache directory given by
#' [tools::R_user_dir()]. `arena_cache_clear()` deletes the generated data;
#' run results are kept.
#'
#' @returns `arena_cache_dir()` returns the path of the data cache.
#'   `arena_cache_clear()` returns it invisibly.
#' @export
arena_cache_dir <- function() {
  file.path(tools::R_user_dir("tidyarena", "cache"), "data")
}

#' @rdname arena_cache_dir
#' @export
arena_cache_clear <- function() {
  dir <- arena_cache_dir()
  unlink(dir, recursive = TRUE)
  cli::cli_inform("Deleted the generated data in {.path {dir}}.")
  invisible(dir)
}

format_n <- function(n) {
  out <- format(as.double(n), scientific = TRUE)
  sub("e\\+0?", "e", sub("\\.0+e", "e", out))
}

# Where the worker loads nanoparquet from. It is tidyarena's own
# dependency, so it may not be in the library paths the backends run with.
reader_lib <- function() {
  dirname(find.package("nanoparquet"))
}
